# Lookup dictionary by ID for O(1) retrieval
CATEGORIES_BY_ID: dict[str, dict[str, Any]] = {
    c["id"]: c for c in (MOOD_CATEGORIES + ACTIVITY_CATEGORIES + GENRE_CATEGORIES)
}


def get_all_categories_data() -> MoodAndGenresData:
    return MoodAndGenresData(
        moods=[CategoryItem(**c) for c in MOOD_CATEGORIES],
        activities=[CategoryItem(**c) for c in ACTIVITY_CATEGORIES],
        genres=[CategoryItem(**c) for c in GENRE_CATEGORIES],
    )


def find_category_by_id(category_id: str) -> CategoryItem | None:
    raw = CATEGORIES_BY_ID.get(category_id.strip().lower())
    if raw:
        return CategoryItem(**raw)
    return None
