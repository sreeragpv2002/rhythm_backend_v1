from typing import Any

from pydantic import BaseModel, Field


class CategoryItem(BaseModel):
    id: str = Field(..., description="Unique slug ID of category")
    name: str = Field(..., description="Display title of the category")
    title: str = Field(..., description="Display title (same as name)")
    type: str = Field(..., description="Category group: 'mood', 'activity', or 'genre'")
    emoji: str | None = Field(default=None, description="Emoji representation")
    image_url: str | None = Field(default=None, description="Artwork or icon image URL")
    gradient: list[str] = Field(default_factory=list, description="Primary & secondary HEX color codes for card backgrounds")
    query: str = Field(..., description="YouTube Music search query used to load songs and playlists")
    description: str | None = Field(default=None, description="Short descriptive tagline")


class MoodAndGenresData(BaseModel):
    moods: list[CategoryItem] = Field(default_factory=list, description="Mood categories")
    activities: list[CategoryItem] = Field(default_factory=list, description="Activity categories")
    genres: list[CategoryItem] = Field(default_factory=list, description="Genre categories")


